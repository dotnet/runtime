# Build and run the native test of the LXR write barrier assembly with MSVC and ml64, then build it again with each
# control and require that the named check fails.
# usage: native-barrier-windows.ps1 -Output <dir> [-Repo <path>]
param(
    [Parameter(Mandatory)][string]$Output,
    [string]$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path
)
$ErrorActionPreference = 'Stop'
New-Item -ItemType Directory -Force $Output | Out-Null
$Output = (Resolve-Path $Output).Path
$gc = Join-Path $Repo 'src\coreclr\gc'
$vm = Join-Path $Repo 'src\coreclr\vm\amd64'
$test = Join-Path $Repo 'docs\design\lxr-port\P21-specialized-barrier\lxr-write-barrier-test.cpp'
$vsenv = "call `"$Repo\eng\native\init-vs-env.cmd`" x64 >nul"

# AsmConstants.inc is generated by the runtime build; use the one of the build tree if given, else an empty stand-in
# (the barrier does not use anything from it).
$inc = Join-Path $Output 'inc'
New-Item -ItemType Directory -Force $inc | Out-Null
Set-Content -Path (Join-Path $inc 'AsmConstants.inc') -Value "; empty stand-in"
Set-Content -Path (Join-Path $inc 'AsmConstantsStub.txt') -Value ''
# AsmMacros.inc names constants of AsmConstants.inc at top level; define the one it needs.
Add-Content -Path (Join-Path $inc 'AsmConstants.inc') -Value "OFFSETOF__RuntimeThreadLocals__ee_alloc_context EQU 0`nOFFSET__TEB__ThreadLocalStoragePointer EQU 58h"

function Build([string]$name, [string]$asmDef, [string]$cxxDef) {
    $obj = Join-Path $Output "$name.asm.obj"
    $exe = Join-Path $Output "$name.exe"
    $log = Join-Path $Output "$name.build.log"
    $cmd = "$vsenv && cd /d `"$Output`" && ml64.exe /nologo /c $asmDef /I`"$inc`" /I`"$vm`" /Fo`"$obj`" `"$gc\amd64\lxr_writebarrier.asm`" && cl.exe /nologo /std:c++17 /EHsc /W4 /WX /wd4100 /wd4324 /O2 /MT $cxxDef /I`"$gc`" `"$test`" `"$gc\lxr_write_barrier.cpp`" `"$obj`" /Fe:`"$exe`""
    & $env:ComSpec /d /s /c $cmd *> $log
    return (Test-Path $exe) -and ($LASTEXITCODE -eq 0)
}

$failed = 0
if (-not (Build 'normal' '' '')) { Get-Content (Join-Path $Output 'normal.build.log') | Select-Object -Last 20; exit 1 }
& (Join-Path $Output 'normal.exe') *> (Join-Path $Output 'normal.log')
if ($LASTEXITCODE -ne 0) { $failed = 1 }
Select-String -Path (Join-Path $Output 'normal.log') -Pattern '^(PASS|FAIL):' | ForEach-Object { $_.Line }

function Control([string]$name, [string]$asmDef, [string]$cxxDef, [string]$check) {
    if (-not (Build $name $asmDef $cxxDef)) { Write-Output "control ${name}: build failed"; $script:failed = 1; return }
    & (Join-Path $Output "$name.exe") *> (Join-Path $Output "$name.log")
    if (Select-String -Path (Join-Path $Output "$name.log") -Pattern "^FAIL: $check" -Quiet) { Write-Output "control ${name}: the check '$check' fails as required" }
    else { Write-Output "control ${name}: the check '$check' did NOT fail"; $script:failed = 1 }
}
Control 'no-vector-save' '/DLXR_WB_CONTROL_NO_VECTOR_SAVE' '' 'vector'
Control 'misalign' '/DLXR_WB_CONTROL_MISALIGN' '' 'alignment'
Control 'no-store-after-slow' '/DLXR_WB_CONTROL_NO_STORE_AFTER_SLOW' '' 'store-after-slow'
Control 'read-old-after-claim' '' '/DLXR_WBTEST_CONTROL_READ_OLD_AFTER_CLAIM' 'old-value-race'
Control 'no-patch' '' '/DLXR_WBTEST_CONTROL_NO_PATCH' 'patch'
Write-Output "barrier native test failed=$failed"
exit $failed
