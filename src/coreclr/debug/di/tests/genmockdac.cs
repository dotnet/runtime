using System;
using System.Globalization;
using System.IO;
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Text;
using System.Text.RegularExpressions;

if (args.Length != 2)
{
    Console.Error.WriteLine("Usage: genmockdac <dacdbiinterface.h> <output.h>");
    return 1;
}

string source = File.ReadAllText(args[0]);
const string BeginMarker = "// BEGIN_MARSHAL";
const string EndMarker = "// END_MARSHAL";
int begin = source.IndexOf(BeginMarker, StringComparison.Ordinal);
int end = begin < 0 ? -1 : source.IndexOf(EndMarker, begin + BeginMarker.Length, StringComparison.Ordinal);
if (begin < 0 || end < 0)
{
    throw new InvalidDataException("Could not find the DAC/DBI interface marshal markers.");
}

source = source.Substring(begin + BeginMarker.Length, end - begin - BeginMarker.Length);
source = Regex.Replace(source, @"//[^\n]*|/\*.*?\*/", "", RegexOptions.Singleline);
MatchCollection methods = Regex.Matches(source,
    @"virtual\s+HRESULT\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*=\s*0\s*;",
    RegexOptions.Singleline);
if (methods.Count == 0 || methods.Count != Regex.Count(source, "STDMETHODCALLTYPE"))
{
    throw new InvalidDataException("Could not parse every DAC/DBI method.");
}

// 32-bit targets return one non-floating-point field in one register. 64-bit targets use up to two
// registers, and allow floating-point fields only when two registers are used.
(int Size, SignatureTypeCode[] Fields, bool Supported32, bool Supported64)[] returnTypes =
[
    (4, [SignatureTypeCode.Int32], true, true),
    (4, [SignatureTypeCode.Int16, SignatureTypeCode.Int16], false, true),
    (8, [SignatureTypeCode.Int64], false, true),
    (8, [SignatureTypeCode.Double], false, false),
    (12, [SignatureTypeCode.Int64, SignatureTypeCode.Int32], false, true),
    (16, [SignatureTypeCode.Double, SignatureTypeCode.Int64], false, true),
    (17, [SignatureTypeCode.Int64, SignatureTypeCode.Int64], false, false),
];
byte[] metadata = CreateReturnTypeMetadata();

using var output = new StreamWriter(args[1], append: false, encoding: new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
output.NewLine = "\n";
output.WriteLine("""
    // Generated by genmockdac.cs. Do not edit.
    class MockDacBase : public IDacDbiInterface
    {
    public:
        HRESULT STDMETHODCALLTYPE QueryInterface(REFIID id, void ** result) override
        {
            *result = nullptr;
            if (id != IID_IUnknown && id != IID_IDacDbiInterface)
                return E_NOINTERFACE;
            *result = static_cast<IDacDbiInterface *>(this);
            AddRef();
            return S_OK;
        }
        ULONG STDMETHODCALLTYPE AddRef() override { return ++m_refs; }
        ULONG STDMETHODCALLTYPE Release() override { return --m_refs; }
    """);
foreach (Match method in methods)
{
    string name = method.Groups[1].Value;
    string parameters = Regex.Replace(method.Groups[2].Value, @"\s+", " ").Trim();
    output.WriteLine($"    HRESULT STDMETHODCALLTYPE {name}({parameters}) override");
    output.WriteLine("    {");
    output.WriteLine($"        fprintf(stderr, \"Unexpected DAC call: {name}\\n\");");
    output.WriteLine("        abort();");
    output.WriteLine("    }");
}
output.WriteLine("""
    private:
        ULONG m_refs = 1;
    };

    static const BYTE s_returnTypeMetadata[] = {
    """);
for (int offset = 0; offset < metadata.Length; offset += 16)
{
    output.Write("    ");
    for (int i = offset; i < Math.Min(offset + 16, metadata.Length); i++)
    {
        output.Write($"0x{metadata[i].ToString("x2", CultureInfo.InvariantCulture)},");
        if (i + 1 < Math.Min(offset + 16, metadata.Length))
        {
            output.Write(' ');
        }
    }
    output.WriteLine();
}
output.WriteLine("""
    };
    struct ReturnTypeCase { ULONG32 size; bool supported32; bool supported64; };
    static const ReturnTypeCase s_returnTypes[] = {
    """);
foreach ((int size, SignatureTypeCode[] _, bool supported32, bool supported64) in returnTypes)
{
    output.WriteLine(FormattableString.Invariant(
        $"    {{{size}, {(supported32 ? "true" : "false")}, {(supported64 ? "true" : "false")}}},"));
}
output.WriteLine("};");

return 0;

byte[] CreateReturnTypeMetadata()
{
    // ECMA-335 II.22 and II.23: metadata tables and field signatures, without executable code.
    // TypeDef row i + 2 is returnTypes[i]; row 1 is <Module>.
    var builder = new MetadataBuilder();
    builder.AddModule(0, builder.GetOrAddString("DBIValueTests"), default, default, default);
    builder.AddTypeDefinition(default, default, builder.GetOrAddString("<Module>"), default,
        MetadataTokens.FieldDefinitionHandle(1), MetadataTokens.MethodDefinitionHandle(1));
    int fieldIndex = 1;
    for (int i = 0; i < returnTypes.Length; i++)
    {
        builder.AddTypeDefinition(TypeAttributes.Public | TypeAttributes.SequentialLayout | TypeAttributes.Sealed,
            default, builder.GetOrAddString(FormattableString.Invariant($"ReturnType{i}")), default,
            MetadataTokens.FieldDefinitionHandle(fieldIndex), MetadataTokens.MethodDefinitionHandle(1));
        SignatureTypeCode[] fields = returnTypes[i].Fields;
        for (int j = 0; j < fields.Length; j++)
        {
            byte[] signature = [(byte)SignatureKind.Field, (byte)fields[j]];
            builder.AddFieldDefinition(FieldAttributes.Public,
                builder.GetOrAddString(FormattableString.Invariant($"Field{j}")),
                builder.GetOrAddBlob(signature));
            fieldIndex++;
        }
    }

    var metadataBlob = new BlobBuilder();
    new MetadataRootBuilder(builder).Serialize(metadataBlob, methodBodyStreamRva: 0, mappedFieldDataStreamRva: 0);
    return metadataBlob.ToArray();
}
