import pathlib
import re
import struct
import sys


ELEMENT_TYPE_I2 = 0x06
ELEMENT_TYPE_I4 = 0x08
ELEMENT_TYPE_I8 = 0x0A
ELEMENT_TYPE_R8 = 0x0D

# Value types for the ReturnValueTypes test: (size, field types, returned by value on 32-bit, on 64-bit).
# 32-bit targets return one non-floating-point field in one register. 64-bit targets use up to two
# registers, and allow floating-point fields only when two registers are used.
RETURN_TYPE_CASES = [
    (4, [ELEMENT_TYPE_I4], True, True),
    (4, [ELEMENT_TYPE_I2, ELEMENT_TYPE_I2], False, True),    # Two fields.
    (8, [ELEMENT_TYPE_I8], False, True),                     # Wider than a 32-bit register.
    (8, [ELEMENT_TYPE_R8], False, False),                    # Floating point in one register.
    (12, [ELEMENT_TYPE_I8, ELEMENT_TYPE_I4], False, True),   # Two 64-bit registers.
    (16, [ELEMENT_TYPE_R8, ELEMENT_TYPE_I8], False, True),   # Floating point in two registers.
    (17, [ELEMENT_TYPE_I8, ELEMENT_TYPE_I8], False, False),  # Larger than two registers.
]

TYPEDEF_FLAGS = 0x109       # tdPublic | tdSequentialLayout | tdSealed: a value-type-like layout.
FIELD_FLAGS = 0x6           # fdPublic
FIELD_SIGNATURE = 0x06      # IMAGE_CEE_CS_CALLCONV_FIELD
PRESENT_TABLES = 0x15       # Module (0), TypeDef (2) and Field (4) tables.
METADATA_SIGNATURE = 0x424A5342  # "BSJB"


def return_type_metadata():
    # Minimal ECMA-335 metadata: Module, TypeDef and Field tables, with no executable code.
    # TypeDef row i + 2 is RETURN_TYPE_CASES[i]; row 1 is <Module>.
    strings = bytearray(b"\0")
    blobs = bytearray(b"\0")

    def string(value):
        offset = len(strings)
        strings.extend(value.encode("ascii") + b"\0")
        return offset

    module = struct.pack("<HHHHH", 0, string("DBIValueTests"), 1, 0, 0)
    types = bytearray(struct.pack("<IHHHHH", 0, string("<Module>"), 0, 0, 1, 1))
    fields = bytearray()
    field_index = 1
    for i, (_, elements, _, _) in enumerate(RETURN_TYPE_CASES):
        types.extend(struct.pack("<IHHHHH", TYPEDEF_FLAGS, string(f"ReturnType{i}"), 0, 0, field_index, 1))
        for j, element in enumerate(elements):
            signature = len(blobs)
            blobs.extend(bytes([2, FIELD_SIGNATURE, element]))
            fields.extend(struct.pack("<HHH", FIELD_FLAGS, string(f"Field{j}"), signature))
            field_index += 1
    tables = struct.pack("<IBBBBQQIII", 0, 2, 0, 0, 1, PRESENT_TABLES, 0, 1, len(RETURN_TYPE_CASES) + 1, field_index - 1)
    tables += module + types + fields
    streams = [(b"#~", tables), (b"#Strings", strings), (b"#Blob", blobs), (b"#GUID", bytes(16))]
    root = struct.pack("<IHHII", METADATA_SIGNATURE, 1, 1, 0, 12) + b"v4.0.30319\0\0" + struct.pack("<HH", 0, len(streams))
    names = [name + bytes(4 - len(name) % 4) for name, _ in streams]
    offset = len(root) + sum(8 + len(name) for name in names)
    headers = bytearray()
    data = bytearray()
    for name, (_, stream) in zip(names, streams):
        headers.extend(struct.pack("<II", offset, len(stream)) + name)
        padded = bytes(stream) + bytes(-len(stream) % 4)
        data.extend(padded)
        offset += len(padded)
    return root + headers + data


def main():
    source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    source = source.split("// BEGIN_MARSHAL", 1)[1].split("// END_MARSHAL", 1)[0]
    source = re.sub(r"//[^\n]*|/\*.*?\*/", "", source, flags=re.DOTALL)
    methods = re.findall(
        r"virtual\s+HRESULT\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*=\s*0\s*;",
        source,
        flags=re.DOTALL,
    )
    if not methods or len(methods) != source.count("STDMETHODCALLTYPE"):
        raise ValueError("Could not parse every DAC/DBI method")

    lines = [
        "// Generated by genmockdac.py. Do not edit.",
        "class MockDacBase : public IDacDbiInterface",
        "{",
        "public:",
        "    HRESULT STDMETHODCALLTYPE QueryInterface(REFIID id, void ** result) override",
        "    {",
        "        *result = nullptr;",
        "        if (id != IID_IUnknown && id != IID_IDacDbiInterface)",
        "            return E_NOINTERFACE;",
        "        *result = static_cast<IDacDbiInterface *>(this);",
        "        AddRef();",
        "        return S_OK;",
        "    }",
        "    ULONG STDMETHODCALLTYPE AddRef() override { return ++m_refs; }",
        "    ULONG STDMETHODCALLTYPE Release() override { return --m_refs; }",
    ]
    for name, parameters in methods:
        parameters = " ".join(parameters.split())
        lines.extend(
            [
                f"    HRESULT STDMETHODCALLTYPE {name}({parameters}) override",
                "    {",
                f'        fprintf(stderr, "Unexpected DAC call: {name}\\n");',
                "        abort();",
                "    }",
            ]
        )
    lines.extend(["private:", "    ULONG m_refs = 1;", "};", ""])
    metadata = return_type_metadata()
    lines.append("static const BYTE s_returnTypeMetadata[] = {")
    for offset in range(0, len(metadata), 16):
        lines.append("    " + ", ".join(f"0x{value:02x}" for value in metadata[offset:offset + 16]) + ",")
    lines.extend(["};", "struct ReturnTypeCase { ULONG32 size; bool supported32; bool supported64; };",
                  "static const ReturnTypeCase s_returnTypes[] = {"])
    for size, _, supported32, supported64 in RETURN_TYPE_CASES:
        lines.append(f"    {{{size}, {str(supported32).lower()}, {str(supported64).lower()}}},")
    lines.extend(["};", ""])
    pathlib.Path(sys.argv[2]).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
