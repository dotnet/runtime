using System;
using System.IO;
using System.Linq;
using System.Text;
using System.Collections.Generic;
using System.Globalization;
using Microsoft.Build.Utilities;
using Microsoft.Build.Framework;
using System.Diagnostics.CodeAnalysis;

using JoinedString;
//
// This class generates the g_wasmThunks array and CallFunc_* functions used by the CoreCLR interpreter to call native code on WASM.
// The generated code should be kept in sync with the corresponding CoreCLR runtime code that consumes these thunks and call functions.
//

#nullable enable

namespace Microsoft.WebAssembly.Build.Tasks.CoreClr;

internal sealed class InterpToNativeGenerator
{
    private LogAdapter Log { get; set; }

    public InterpToNativeGenerator(LogAdapter log) => Log = log;

    public void Generate(IEnumerable<string> cookies, string outputPath)
    {
        using TempFileName tmpFileName = new();
        using (var w = File.CreateText(tmpFileName.Path))
        {
            Emit(w, cookies);
        }

        if (Utils.CopyIfDifferent(tmpFileName.Path, outputPath, useHash: false))
            Log.LogMessage(MessageImportance.Low, $"Generating managed2native table to '{outputPath}'.");
        else
            Log.LogMessage(MessageImportance.Low, $"Managed2native table in {outputPath} is unchanged.");
    }

    private static string SignatureToArguments(string signature)
    {
        var tokens = SignatureMapper.ParseSignatureTokens(signature);
        if (tokens.Count <= 1)
            return "void";

        return string.Join(", ", tokens.Skip(1).Select(static t => SignatureMapper.TokenToNativeType(t)));
    }

    private static string CallFuncName(IEnumerable<string> args, string result, bool isPortableEntryPointCall)
    {
        var paramTypes = args.Any() ? string.Join("_", args.Select(static t => SignatureMapper.TokenToNameType(t))) : "Void";

        return $"CallFunc_{paramTypes}_Ret{result}{(isPortableEntryPointCall ? "_PE" : "")}";
    }

    /// <summary>
    /// Emits the R2R-to-interpreter side of the portable entrypoint boundary: the thunks that
    /// <c>g_wasmThunks</c>' <c>_PE</c> helpers call into. Struct returns are not emitted yet; their
    /// wasm sret convention across this boundary is not settled, and no <c>_PE</c> helper exercises one.
    /// </summary>
    public void GeneratePortableEntryPoints(IEnumerable<string> cookies, string outputPath)
    {
        using TempFileName tmpFileName = new();
        using (var w = File.CreateText(tmpFileName.Path))
        {
            EmitPortableEntryPoints(w, cookies);
        }

        if (Utils.CopyIfDifferent(tmpFileName.Path, outputPath, useHash: false))
            Log.LogMessage(MessageImportance.Low, $"Generating portable entrypoint thunks to '{outputPath}'.");
        else
            Log.LogMessage(MessageImportance.Low, $"Portable entrypoint thunks in {outputPath} are unchanged.");
    }

    private static string CallInterpreterName(IEnumerable<string> args, string result)
    {
        var paramTypes = args.Any() ? string.Join("_", args.Select(static t => SignatureMapper.TokenToNameType(t))) : "Void";

        return $"CallInterpreter_{paramTypes}_Ret{result}";
    }

    private static bool IsStructToken(string token) => PortableEntryPointThunkSignature.IsStructToken(token);

    private static void EmitPortableEntryPoints(StreamWriter w, IEnumerable<string> cookies)
    {
        var signatures = cookies.Distinct().OrderBy(c => c, StringComparer.Ordinal).ToArray();

        w.Write(
        """
        // Licensed to the .NET Foundation under one or more agreements.
        // The .NET Foundation licenses this file to you under the MIT license.
        //

        //
        // GENERATED FILE, DON'T EDIT
        // Generated by coreclr InterpToNativeGenerator
        //

        #include <interpretershared.h>
        #include <interpexec.h>
        #include "callhelpers.hpp"

        void ExecuteInterpretedMethodWithArgs_PortableEntryPoint(PCODE portableEntrypoint, TransitionBlock* block, size_t argsSize, int8_t* retBuff);

        namespace
        {

        """);

        var emitted = new List<(string Key, string Name)>();

        foreach (var signature in signatures)
        {
            var tokens = SignatureMapper.ParseSignatureTokens(signature);
            if (!IsPortableEntryPointCall(tokens))
                continue;

            string returnToken = tokens[0];

            tokens.RemoveAt(tokens.Count - 1);
            RemoveAsyncCallMarker(tokens);
            var args = Args(tokens);

            string retName = SignatureMapper.TokenToNameType(returnToken);
            string name = CallInterpreterName(args, retName);
            if (emitted.Any(e => e.Name == name))
                continue;

            // crossgen2 passes a struct return through an explicit buffer parameter rather than by value.
            // Returning the struct by value instead would make the compiler insert its own sret pointer
            // ahead of callersStackPointer, silently transposing the two.
            bool isStructReturn = IsStructToken(returnToken);
            string retType = isStructReturn ? "void" : SignatureMapper.TokenToNativeType(returnToken);
            bool isVoid = isStructReturn || returnToken == "v";

            var parameters = PortableEntryPointThunkSignature.GetDeclaredParameters(args, isStructReturn);
            var declTypes = parameters.Select(static p => p.NativeType).ToList();
            var namedArgs = parameters.Select(static p => $"{p.NativeType} {p.Name}").ToList();

            int slot = 0;
            var stores = new List<string>();
            for (int i = 0; i < args.Count; i++)
            {
                string t = args[i];
                if (t[0] == 'A')
                    slot = (slot + 1) & ~1;

                // A float or double occupies its slot as itself: casting to int64_t would convert the
                // value rather than store its bits, and the interpreter reads the slot back through
                // ARG_F32/ARG_F64.
                stores.Add(t switch
                {
                    _ when IsStructToken(t) => $"        memcpy(&transitionBlock.args[{slot}], arg{i}, {SignatureMapper.GetStructSize(t)});",
                    "f" => $"        *(float*)&transitionBlock.args[{slot}] = arg{i};",
                    "d" => $"        *(double*)&transitionBlock.args[{slot}] = arg{i};",
                    _ => $"        transitionBlock.args[{slot}] = (int64_t)arg{i};",
                });

                slot += SignatureMapper.TokenToSlotCount(t);
            }

            string declArgs = declTypes.Count > 0 ? ", " + string.Join(", ", declTypes) : "";
            string sigArgs = namedArgs.Count > 0 ? string.Join(", ", namedArgs) + ", " : "";

            w.WriteLine($"    FCDECL{declTypes.Count}({retType}, {name}{declArgs});");
            w.WriteLine($"    WASM_CALLABLE_FUNC_{declTypes.Count + 1}({retType}, {name}, {sigArgs}PCODE portableEntrypoint)");
            w.WriteLine("    {");
            w.WriteLine("        struct");
            w.WriteLine("        {");
            w.WriteLine("            TransitionBlock block;");
            if (slot > 0)
                w.WriteLine($"            int64_t args[{slot}];");
            w.WriteLine("        } transitionBlock;");
            w.WriteLine("        transitionBlock.block.m_ReturnAddress = 0;");
            w.WriteLine("        transitionBlock.block.m_StackPointer = callersStackPointer;");
            foreach (var store in stores)
                w.WriteLine(store);
            if (slot > 0)
                w.WriteLine("        static_assert(offsetof(decltype(transitionBlock), args) == sizeof(TransitionBlock), \"Args array must be at a TransitionBlock offset from the start of the block\");");
            w.WriteLine();
            if (!isStructReturn)
                w.WriteLine(isVoid ? "        void * result = NULL;" : $"        {retType} result = 0;");
            string retBuffArg = isStructReturn ? "retBuf" : "(int8_t*)&result";
            w.WriteLine($"        ExecuteInterpretedMethodWithArgs_PortableEntryPoint(portableEntrypoint, &transitionBlock.block, {(slot > 0 ? "sizeof(transitionBlock.args)" : "0")}, {retBuffArg});");
            w.WriteLine(isVoid ? "        return;" : "        return result;");
            w.WriteLine("    }");
            w.WriteLine();

            emitted.Add(("I" + signature, name));
        }

        w.WriteLine("}");
        w.WriteLine();
        w.WriteLine("const StringToWasmSigThunk g_wasmGeneratedPortableEntryPointThunks[] = {");
        foreach (var (key, name) in emitted)
            w.WriteLine($"    {{ \"{key}\", (void*)&{name} }},");
        w.WriteLine("};");
        w.WriteLine();
        w.WriteLine("const size_t g_wasmGeneratedPortableEntryPointThunksCount = sizeof(g_wasmGeneratedPortableEntryPointThunks) / sizeof(g_wasmGeneratedPortableEntryPointThunks[0]);");
    }

    private static void Emit(StreamWriter w, IEnumerable<string> cookies)
    {
        // Use OrderBy because Order() is not available on .NET Framework
        var signatures = cookies.OrderBy(c => c).Distinct().ToArray();
        Array.Sort(signatures, StringComparer.Ordinal);

        // Collect unique struct return sizes so we can emit typedefs
        var structReturnSizes = new SortedSet<int>();
        foreach (var sig in signatures)
        {
            var toks = SignatureMapper.ParseSignatureTokens(sig);
            if (toks[0][0] == 'S' && toks[0].Length > 1)
                structReturnSizes.Add(SignatureMapper.GetStructSize(toks[0]));
        }

        w.Write(
        """
        // Licensed to the .NET Foundation under one or more agreements.
        // The .NET Foundation licenses this file to you under the MIT license.
        //

        //
        // GENERATED FILE, DON'T EDIT
        // Generated by coreclr InterpToNativeGenerator
        //

        #include <callhelpers.hpp>
        #include <minipal/utils.h>

        // Arguments are passed on the stack with each argument aligned to INTERP_STACK_SLOT_SIZE.
        #define ARG_ADDR(i) (pArgs + (i * INTERP_STACK_SLOT_SIZE))
        #define ARG_IND(i) ((int32_t)((int32_t*)ARG_ADDR(i)))
        #define ARG_I32(i) (*(int32_t*)ARG_ADDR(i))
        #define ARG_I64(i) (*(int64_t*)ARG_ADDR(i))
        #define ARG_F32(i) (*(float*)ARG_ADDR(i))
        #define ARG_F64(i) (*(double*)ARG_ADDR(i))

        """);

        // Emit typedefs for struct return types so emcc generates the correct sret ABI
        foreach (var size in structReturnSizes)
        {
            w.WriteLine($"typedef struct {{ char d[{size}]; }} wasm_ret_S{size};");
        }

        w.Write(
        """

        namespace
        {
        """);

        foreach (var signatureValue in signatures)
        {
            string signature = signatureValue;
            try
            {
                var tokens = SignatureMapper.ParseSignatureTokens(signature);
                string returnToken = tokens[0];
                var result = Result(returnToken);
                bool isPortableEntryPointCall = IsPortableEntryPointCall(tokens);
                if (isPortableEntryPointCall)
                {
                    // Portable entrypoints have an extra hidden parameter for the portable entrypoint context, so we need to adjust the signature and result accordingly for the call function generation
                    tokens.RemoveAt(tokens.Count - 1);
                }

                RemoveAsyncCallMarker(tokens);

                var args = Args(tokens);

                var argTypes = args.Select(static t => SignatureMapper.TokenToNativeType(t)).ToList();
                var argValues = ArgsWithSlotOffsets(args).ToList();

                // R2R code takes a struct return through an explicit buffer that follows the stack
                // pointer and 'this', so the pointer this calls through must spell it out. Declaring
                // the call as returning the struct would make the compiler insert its own sret
                // pointer at parameter 0 instead, ahead of the stack pointer. Native callees keep the
                // by-value form, which is what their own C ABI gives them.
                bool isStructReturn = isPortableEntryPointCall && IsStructToken(returnToken);
                if (isStructReturn)
                {
                    argTypes.Insert(args.Count > 0 && args[0] == "T" ? 1 : 0, "int8_t*");
                    argValues.Insert(args.Count > 0 && args[0] == "T" ? 1 : 0, "pRet");
                }

                string fptrReturn = isStructReturn ? "void" : result.nativeType;
                string assignResult = isStructReturn || result.isVoid ? "" : $"*(({result.nativeType}*)pRet) = ";

                var portableEntryPointComma = argTypes.Count > 0 ? ", " : "";
                var portableEntrypointDeclaration = isPortableEntryPointCall ? portableEntryPointComma + "PCODE" : "";
                var portableEntrypointParam = isPortableEntryPointCall ? portableEntryPointComma + "pPortableEntryPoint" : "";
                var portableEntrypointStackDeclaration = isPortableEntryPointCall ? "int*, " : "";
                var portableEntrypointStackParam = isPortableEntryPointCall ? "&framePointer, " : "";
                var portableEntrypointPointerRD = isPortableEntryPointCall ? "*" : "";
                w.Write(
                    $$"""

                        {{(isPortableEntryPointCall ? "NOINLINE " : "")}}static void {{CallFuncName(args, SignatureMapper.TokenToNameType(returnToken), isPortableEntryPointCall)}}(PCODE {{(isPortableEntryPointCall ? "pPortableEntryPoint" : "pcode")}}, int8_t* pArgs, int8_t* pRet)
                        {{{(isPortableEntryPointCall ? "\n        alignas(16) int framePointer = TERMINATE_R2R_STACK_WALK;" : "")}}
                            {{fptrReturn}} (*fptr)({{portableEntrypointStackDeclaration}}{{string.Join(", ", argTypes)}}{{portableEntrypointDeclaration}}) = {{portableEntrypointPointerRD}}({{fptrReturn}} ({{portableEntrypointPointerRD}}*)({{portableEntrypointStackDeclaration}}{{string.Join(", ", argTypes)}}{{portableEntrypointDeclaration}})){{(isPortableEntryPointCall ? "(pPortableEntryPoint)" : "pcode")}};
                            {{assignResult}}(*fptr)({{portableEntrypointStackParam}}{{string.Join(", ", argValues)}}{{portableEntrypointParam}});
                        }

                    """);
            }
            catch (InvalidSignatureCharException e)
            {
                throw new LogAsErrorException($"Element '{e.Char}' of signature '{signature}' can't be handled by managed2native generator");
            }
        }

        w.Write(
            $$"""
            }

            const StringToWasmSigThunk g_wasmThunks[] = {
            {{signatures.Join($",{w.NewLine}", signature =>
            {
                string initialSignature = signature;
                var tokens = SignatureMapper.ParseSignatureTokens(signature);
                bool isPortableEntryPointCall = IsPortableEntryPointCall(tokens);
                if (isPortableEntryPointCall)
                    tokens.RemoveAt(tokens.Count - 1);
                RemoveAsyncCallMarker(tokens);
                return $"    {{ \"M{initialSignature}\", (void*)&{CallFuncName(Args(tokens), SignatureMapper.TokenToNameType(tokens[0]), isPortableEntryPointCall)} }}";
            }
            )}}
            };

            const size_t g_wasmThunksCount = sizeof(g_wasmThunks) / sizeof(g_wasmThunks[0]);

            """);

        static List<string> ArgsWithSlotOffsets(List<string> args)
        {
            var result = new List<string>();
            int slot = 0;
            foreach (var token in args)
            {
                if (token[0] == 'A')
                {
                    slot = (slot + 1) & ~1;
                }

                result.Add($"{SignatureMapper.TokenToArgType(token)}({slot})");
                slot += SignatureMapper.TokenToSlotCount(token);
            }

            return result;
        }

        static (bool isVoid, string nativeType) Result(string returnToken)
        {
            // For struct returns, use the typedef so emcc generates the correct sret ABI
            if (returnToken[0] == 'S' && returnToken.Length > 1)
                return (false, $"wasm_ret_S{SignatureMapper.GetStructSize(returnToken)}");
            return new(returnToken == "v", SignatureMapper.TokenToNativeType(returnToken));
        }

    }

    private static List<string> Args(List<string> tokens)
    {
        return tokens.Count > 1 ? tokens.GetRange(1, tokens.Count - 1) : new List<string>();
    }

    private static bool IsPortableEntryPointCall(List<string> tokens)
    {
        return tokens.Count > 0 && tokens[tokens.Count - 1] == "p";
    }

    private static bool RemoveAsyncCallMarker(List<string> tokens)
    {
        int asyncMarkerIndex = tokens.IndexOf("a");
        if (asyncMarkerIndex < 0)
            return false;

        tokens.RemoveAt(asyncMarkerIndex);
        return true;
    }
}
