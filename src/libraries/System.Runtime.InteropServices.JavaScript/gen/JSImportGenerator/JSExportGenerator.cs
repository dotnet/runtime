using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Diagnostics;
using System.Globalization;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Microsoft.Interop.JavaScript
{
    [Generator]
    public sealed class JSExportGenerator : IIncrementalGenerator
    {
        internal sealed record IncrementalStubGenerationContext(
            JSSignatureContext SignatureContext,
            ContainingSyntaxContext ContainingSyntaxContext,
            MethodSignatureDiagnosticLocations DiagnosticLocation,
            JSExportData JSExportData,
            bool IsReflectionFree,
            string? UnsafeAccessorTarget);

        internal static bool CanUseUnsafeAccessor(INamedTypeSymbol type)
        {
            for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            {
                if (current.Arity != 0 || current.IsFileLocal)
                    return false;
            }
            return true;
        }

        /// <summary>
        /// Whether the wrapper can be named from the generated registration, which requires every
        /// containing type to be visible to it.
        /// </summary>
        internal static bool IsReferenceableByMethodGroup(INamedTypeSymbol? type)
        {
            for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            {
                if (current.Arity != 0
                    || current.IsFileLocal
                    || current.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
                {
                    return false;
                }
            }
            return true;
        }

        public static class StepNames
        {
            public const string CalculateStubInformation = nameof(CalculateStubInformation);
            public const string GenerateSingleStub = nameof(GenerateSingleStub);
        }

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var assemblyInfo = context.CompilationProvider.Select(static (compilation, ct) =>
                (Name: compilation.AssemblyName, Targets: GetTypeMapAssemblyTargets(compilation)));
            var methodsToGenerate = context.SyntaxProvider
                .ForAttributeWithMetadataName(Constants.JSExportAttribute,
                    static (node, ct) => node is MethodDeclarationSyntax,
                    static (context, ct) => new { Syntax = (MethodDeclarationSyntax)context.TargetNode, Symbol = (IMethodSymbol)context.TargetSymbol })
                .Where(static data =>
                    JSInteropDiagnosticsAnalyzer.GetDiagnosticIfInvalidMethodForGeneration(
                        data.Syntax, data.Symbol,
                        GeneratorDiagnostics.InvalidExportAttributedMethodSignature,
                        GeneratorDiagnostics.InvalidExportAttributedMethodContainingTypeMissingModifiers,
                        requiresImplementation: true) is null);

            IncrementalValueProvider<StubEnvironment> stubEnvironment = context.CreateStubEnvironmentProvider();
            IncrementalValuesProvider<(string Source, string Registration, string? Attribute, string Name, int Hash, string Signature)> generateSingleStub = methodsToGenerate
                .Combine(stubEnvironment)
                .Select(static (data, ct) => CalculateStubInformation(data.Left.Syntax, data.Left.Symbol, data.Right, ct))
                .WithTrackingName(StepNames.CalculateStubInformation)
                .Select(static (data, ct) => GenerateSource(data))
                .WithTrackingName(StepNames.GenerateSingleStub);

            context.RegisterSourceOutput(generateSingleStub.Collect().Combine(assemblyInfo), static (context, data) =>
            {
                if (data.Left.IsEmpty && data.Right.Targets.Length == 0)
                {
                    return;
                }

                var writer = new IndentedTextWriter();
                writer.WriteLine("// <auto-generated/>");
                writer.Write(data.Right.Targets);
                if (!data.Left.IsEmpty)
                {
                    WriteProviderSource(writer, data.Left, data.Right.Name);
                }
                foreach (var generated in data.Left)
                {
                    writer.Write(generated.Source);
                }
                context.AddSource("JSExports.g.cs", writer.ToString());
            });
        }

        private static string GetTypeMapAssemblyTargets(Compilation compilation)
        {
            var writer = new IndentedTextWriter();
            foreach (IAssemblySymbol assembly in compilation.SourceModule.ReferencedAssemblySymbols.OrderBy(static assembly => assembly.Name, StringComparer.Ordinal))
            {
                if (assembly.GetAttributes().Any(static attribute =>
                    attribute.AttributeClass is { Name: "TypeMapAttribute" or "TypeMapAssemblyTargetAttribute", TypeArguments.Length: 1 } type
                    && type.ContainingNamespace.ToDisplayString() == "System.Runtime.InteropServices"
                    && type.TypeArguments[0].ToDisplayString() == Constants.JSExportProvider))
                {
                    writer.WriteLine($"[assembly: global::System.Runtime.InteropServices.TypeMapAssemblyTargetAttribute<{Constants.JSExportProviderGlobal}>({CodeWriterHelpers.StringLiteral(assembly.Name)})]");
                }
            }
            return writer.ToString();
        }

        private static JSExportData? ProcessJSExportAttribute(AttributeData attrData)
        {
            if (attrData.AttributeClass?.TypeKind is null or TypeKind.Error)
            {
                return null;
            }

            return new JSExportData();
        }

        private static IncrementalStubGenerationContext CalculateStubInformation(
            MethodDeclarationSyntax originalSyntax,
            IMethodSymbol symbol,
            StubEnvironment environment,
            CancellationToken ct)
        {
            ct.ThrowIfCancellationRequested();
            AttributeData? jsExportAttr = null;
            foreach (AttributeData attr in symbol.GetAttributes())
            {
                if (attr.AttributeClass is not null
                    && attr.AttributeClass.ToDisplayString() == Constants.JSExportAttribute)
                {
                    jsExportAttr = attr;
                }
            }

            Debug.Assert(jsExportAttr is not null);

            var locations = new MethodSignatureDiagnosticLocations(originalSyntax);
            var generatorDiagnostics = new GeneratorDiagnosticsBag(new DescriptorProvider(), locations, SR.ResourceManager, typeof(FxResources.Microsoft.Interop.JavaScript.JSImportGenerator.SR));
            JSExportData jsExportData = ProcessJSExportAttribute(jsExportAttr!) ?? new JSExportData();
            var signatureContext = JSSignatureContext.Create(symbol, environment, generatorDiagnostics, ct);
            ContainingSyntaxContext containingTypeContext = originalSyntax.GetContainingSyntaxContext();

            string? accessorTarget = null;
            if (!IsReferenceableByMethodGroup(symbol.ContainingType) && CanUseUnsafeAccessor(symbol.ContainingType))
            {
                var names = new List<string>();
                for (INamedTypeSymbol? type = symbol.ContainingType; type is not null; type = type.ContainingType)
                    names.Insert(0, type.MetadataName);
                string typeName = string.Join("+", names);
                for (INamespaceSymbol ns = symbol.ContainingNamespace; !ns.IsGlobalNamespace; ns = ns.ContainingNamespace)
                    typeName = ns.MetadataName + "." + typeName;
                accessorTarget = typeName + ", " + symbol.ContainingAssembly.Identity.GetDisplayName();
            }
            return new IncrementalStubGenerationContext(signatureContext, containingTypeContext, locations, jsExportData,
                IsReferenceableByMethodGroup(symbol.ContainingType), accessorTarget);
        }

        private static void WriteProviderSource(
            IndentedTextWriter writer,
            ImmutableArray<(string Source, string Registration, string? Attribute, string Name, int Hash, string Signature)> methods,
            string assemblyName)
        {
            const string GeneratedNamespace = "System.Runtime.InteropServices.JavaScript";
            const string ProviderClass = "__GeneratedJSExportProvider";
            writer.WriteLine($"[assembly: global::System.Runtime.InteropServices.TypeMapAttribute<{Constants.JSExportProviderGlobal}>({CodeWriterHelpers.StringLiteral(assemblyName)}, typeof(global::{GeneratedNamespace}.{ProviderClass}))]");
            writer.WriteLine($"namespace {GeneratedNamespace}");
            using (writer.WriteBlock())
            {
                writer.WriteLine($"[{Constants.CompilerGeneratedAttributeGlobal}]");
                writer.WriteLine($"file sealed class {ProviderClass} : {Constants.JSExportProviderGlobal}");
                using (writer.WriteBlock())
                {
                    writer.WriteLine($"public {ProviderClass}()");
                    using (writer.WriteBlock())
                    {
                    }
                    writer.WriteLine();
                    writer.WriteLine($"[{Constants.DynamicDependencyAttributeGlobal}({Constants.DynamicallyAccessedMemberTypesGlobal}.PublicParameterlessConstructor, typeof({ProviderClass}))]");
                    writer.WriteLine($"[{Constants.DebuggerNonUserCodeAttribute}]");
                    writer.WriteLine("public override global::System.ReadOnlySpan<string> GetExportNames()");
                    using (writer.WriteBlock())
                    {
                        writer.WriteLine("unsafe");
                        using (writer.WriteBlock())
                        {
                            foreach (var method in methods)
                            {
                                writer.WriteLine($"__RegisterSignature(this, {method.Signature});");
                            }
                        }
                        string names = string.Join(", ", methods.Select(static method =>
                            CodeWriterHelpers.StringLiteral($"{method.Name}#{method.Hash.ToString(CultureInfo.InvariantCulture)}")));
                        writer.WriteLine($"return new string[] {{ {names} }};");
                        writer.WriteLine();
                        writer.WriteLine("[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"RegisterSignature\")]");
                        writer.WriteLine($"static unsafe extern void __RegisterSignature({Constants.JSExportProviderGlobal} provider, global::System.ReadOnlySpan<{Constants.JSMarshalerTypeGlobal}> signatures);");
                    }
                    writer.WriteLine();
                    foreach (var method in methods)
                    {
                        if (method.Attribute is not null)
                        {
                            writer.WriteLine($"[{method.Attribute}]");
                        }
                    }
                    writer.WriteLine($"[{Constants.DebuggerNonUserCodeAttribute}]");
                    writer.WriteLine("public override void Bind(string methodId)");
                    using (writer.WriteBlock())
                    {
                        writer.WriteLine("switch (methodId)");
                        using (writer.WriteBlock())
                        {
                            for (int i = 0; i < methods.Length; i++)
                            {
                                writer.WriteLine($"case {CodeWriterHelpers.StringLiteral(i.ToString(CultureInfo.InvariantCulture))}:");
                                writer.Indent++;
                                writer.WriteLine("unsafe");
                                using (writer.WriteBlock())
                                {
                                    writer.WriteLine(methods[i].Registration);
                                }
                                writer.WriteLine("return;");
                                writer.Indent--;
                            }
                            writer.WriteLine("default:");
                            writer.Indent++;
                            writer.WriteLine("throw new global::System.ArgumentOutOfRangeException(nameof(methodId), methodId, null);");
                            writer.Indent--;
                        }
                    }
                }
            }
        }

        private static (string Source, string Registration, string? Attribute, string Name, int Hash, string Signature) GenerateSource(IncrementalStubGenerationContext incrementalContext)
        {
            var diagnostics = new GeneratorDiagnosticsBag(new DescriptorProvider(), incrementalContext.DiagnosticLocation, SR.ResourceManager, typeof(FxResources.Microsoft.Interop.JavaScript.JSImportGenerator.SR));
            ImmutableArray<TypePositionInfo> signatureElements = incrementalContext.SignatureContext.SignatureContext.ElementTypeInformation;
            ImmutableArray<TypePositionInfo> allElements = signatureElements.Add(new TypePositionInfo(
                new ReferenceTypeInfo(Constants.ExceptionGlobal, Constants.ExceptionGlobal),
                new JSMarshallingInfo(NoMarshallingInfo.Instance, new JSSimpleTypeInfo(KnownManagedType.Exception, Constants.ExceptionGlobal))
                {
                    JSType = System.Runtime.InteropServices.JavaScript.JSTypeFlags.Error,
                })
            {
                InstanceIdentifier = Constants.ArgumentException,
                ManagedIndex = TypePositionInfo.ExceptionIndex,
                NativeIndex = signatureElements.Length,
                RefKind = RefKind.Out,
                IsErrorHandlingPosition = true,
            });

            for (int i = 0; i < allElements.Length; i++)
            {
                if (allElements[i].IsNativeReturnPosition && allElements[i].ManagedType != SpecialTypeInfo.Void)
                {
                    // Passing the return slot by reference preserves partial runtime initialization.
                    allElements = allElements.SetItem(i, allElements[i] with
                    {
                        ManagedIndex = TypePositionInfo.ReturnIndex,
                        NativeIndex = allElements.Length,
                        RefKind = RefKind.Out,
                    });
                }
            }

            var stubGenerator = new UnmanagedToManagedStubGenerator(
                allElements,
                diagnostics,
                new CompositeMarshallingGeneratorResolver(
                    new NoSpanAndTaskMixingResolver(),
                    new JSGeneratorResolver()));

            var writer = new IndentedTextWriter();
            incrementalContext.ContainingSyntaxContext.WriteTo(
                writer,
                (Context: incrementalContext, Generator: stubGenerator),
                static (writer, state) => WriteWrapper(writer, state.Context, state.Generator));

            JSSignatureContext signature = incrementalContext.SignatureContext;
            string signatures = SignatureBindingHelpers.CreateSignaturesArgument(signatureElements, StubCodeContext.DefaultNativeToManagedStub);

            if (incrementalContext.IsReflectionFree)
            {
                string wrapperReference = $"&{signature.StubTypeQualifiedName}.{signature.WrapperName}";
                string fastRegistration = $"{Constants.JSFunctionSignatureGlobal}.{Constants.BindCSFunctionMethod}({CodeWriterHelpers.StringLiteral(signature.QualifiedMethodName)}, {signature.TypesHash.ToString(CultureInfo.InvariantCulture)}, {signatures}, {wrapperReference});";
                return (writer.ToString(), fastRegistration, null, signature.QualifiedMethodName, signature.TypesHash, signatures);
            }

            if (incrementalContext.UnsafeAccessorTarget is string target)
            {
                string accessorRegistration =
                    $"{Constants.JSFunctionSignatureGlobal}.{Constants.BindCSFunctionMethod}({CodeWriterHelpers.StringLiteral(signature.QualifiedMethodName)}, {signature.TypesHash.ToString(CultureInfo.InvariantCulture)}, {signatures}, &__Invoke);\n" +
                    $"static void __Invoke({Constants.JSMarshalerArgumentGlobal}* arguments) => __Access(null, arguments);\n" +
                    $"[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = {CodeWriterHelpers.StringLiteral(signature.WrapperName)})]\n" +
                    $"static extern void __Access([global::System.Runtime.CompilerServices.UnsafeAccessorType({CodeWriterHelpers.StringLiteral(target)})] object target, {Constants.JSMarshalerArgumentGlobal}* arguments);";
                return (writer.ToString(), accessorRegistration, null, signature.QualifiedMethodName, signature.TypesHash, signatures);
            }

            // Generic and file-local containing types cannot be targeted by this accessor.
            string registration = $"{Constants.JSFunctionSignatureGlobal}.{Constants.BindCSFunctionMethod}({CodeWriterHelpers.StringLiteral(signature.QualifiedMethodName)}, {signature.TypesHash.ToString(CultureInfo.InvariantCulture)}, {signatures});";
            string attribute = $"{Constants.DynamicDependencyAttributeGlobal}({CodeWriterHelpers.StringLiteral(signature.WrapperName)}, {CodeWriterHelpers.StringLiteral(signature.StubTypeFullName)}, {CodeWriterHelpers.StringLiteral(signature.AssemblyName)})";

            return (writer.ToString(), registration, attribute, signature.QualifiedMethodName, signature.TypesHash, signatures);
        }

        private static void WriteWrapper(
            IndentedTextWriter writer,
            IncrementalStubGenerationContext context,
            UnmanagedToManagedStubGenerator stubGenerator)
        {
            const string InnerWrapperName = "__Stub";
            writer.WriteLine($"[{Constants.DebuggerNonUserCodeAttribute}]");
            writer.WriteLine($"internal static unsafe void {context.SignatureContext.WrapperName}({Constants.JSMarshalerArgumentGlobal}* {Constants.ArgumentsBuffer})");
            using (writer.WriteBlock())
            {
                writer.WriteLine("unsafe");
                using (writer.WriteBlock())
                {
                    WriteWrapperBody(writer, context, stubGenerator, InnerWrapperName);
                }
            }
        }

        private static void WriteWrapperBody(
            IndentedTextWriter writer,
            IncrementalStubGenerationContext context,
            UnmanagedToManagedStubGenerator stubGenerator,
            string innerWrapperName)
        {
            WriteWrapperToInnerStubCall(writer, context.SignatureContext.SignatureContext.ElementTypeInformation, innerWrapperName);
            GeneratedMethodSignature signature = stubGenerator.GenerateAbiMethodSignatureData();
            writer.WriteLine($"[{Constants.DebuggerNonUserCodeAttribute}]");
            writer.WriteLine($"{signature.ReturnType} {innerWrapperName}{signature.ParameterList}");
            writer.Write(stubGenerator.GenerateStubBodyForMethod(context.SignatureContext.MethodName));
        }

        private static void WriteWrapperToInnerStubCall(
            IndentedTextWriter writer,
            ImmutableArray<TypePositionInfo> signatureElements,
            string innerWrapperName)
        {
            writer.Write($"{innerWrapperName}(");
            bool hasReturn = true;
            foreach (TypePositionInfo nativeArgument in signatureElements.Where(static element => element.NativeIndex != TypePositionInfo.UnsetIndex).OrderBy(static element => element.NativeIndex))
            {
                if (nativeArgument.IsNativeReturnPosition)
                {
                    hasReturn = nativeArgument.ManagedType != SpecialTypeInfo.Void;
                    continue;
                }
                writer.Write($"{Constants.ArgumentsBuffer}[{nativeArgument.NativeIndex + 2}], ");
            }
            writer.Write(Constants.ArgumentsBuffer);
            if (hasReturn)
            {
                writer.Write($", {Constants.ArgumentsBuffer} + 1");
            }
            writer.WriteLine(");");
        }
    }
