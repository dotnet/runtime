/// <summary>
/// An element of the insert-and-copy command lookup table. The C struct
/// <c>{ uint8 insert_len_extra_bits; uint8 copy_len_extra_bits; int8 distance_code; uint8 context;
/// uint16 insert_len_offset; uint16 copy_len_offset; }</c> is packed into a single little-endian 64-bit value.
/// </summary>
internal readonly struct CmdLutElement
{
    private readonly ulong _packed;

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    public CmdLutElement(ulong packed) => _packed = packed;

    public uint InsertLenExtraBits
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (uint)_packed & 0xFF;
    }

    public uint CopyLenExtraBits
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (uint)(_packed >> 8) & 0xFF;
    }

    public int DistanceCode
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (sbyte)(_packed >> 16);
    }

    public int Context
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (int)(_packed >> 24) & 0xFF;
    }

    public int InsertLenOffset
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (int)(_packed >> 32) & 0xFFFF;
    }

    public int CopyLenOffset
    {
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        get => (int)(_packed >> 48);
    }
}

